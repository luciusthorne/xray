"""Go programs: functions, files and lines from .gopclntab, source from the Go
module proxy and the Go repository.

Every Go binary carries the runtime's function table (.gopclntab), even when
stripped: each function's name, entry address, file and start line. With the
build information (.go.buildinfo: Go version, main module and version,
dependency versions) that is enough to name the exact source of every
function. Nothing is built or run.
"""

import re
import struct
import subprocess
from dataclasses import dataclass

_DEP = re.compile(r"^(?P<module>[^@\s]+)@(?P<version>v[^/\s]+)/(?P<inner>.+)$")
_SEMVER = re.compile(r"^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$")
_GO_TAG = re.compile(r"^go\d+\.\d+(?:\.\d+)?(?:(?:rc|beta)\d+)?")
_MAX_ZIP_BYTES = 256 * 1024 * 1024
PROXY = "https://proxy.golang.org"
GO_SOURCE = "https://raw.githubusercontent.com/golang/go/{tag}/src/{inner}"


@dataclass(frozen=True)
class GoInfo:
    go_version: str | None   # go1.27.2
    module: str | None       # github.com/junegunn/fzf
    version: str | None      # v0.74.5+dirty
    revision: str | None     # vcs.revision


def _section_headers(path):
    """{name: (address, offset, size)} from readelf -SW."""

    try:
        text = subprocess.run(["readelf", "-SW", str(path)], capture_output=True, text=True,
                              errors="replace", check=False, timeout=30).stdout
    except (OSError, subprocess.SubprocessError):
        return {}
    out = {}
    for match in re.finditer(r"\]\s+(\S+)\s+\S+\s+([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)", text):
        out[match.group(1)] = tuple(int(match.group(i), 16) for i in (2, 3, 4))
    return out


def parse_pclntab(data, text_start=None):
    """[(address, size, name, file, line)] from a Go 1.18+ pclntab.

    Addresses are text_start + each function's offset; with text_start None
    they are the raw offsets, and the header's own textStart is returned
    alongside by pclntab_text_start.

    Layout: magic, pad, minLC, ptrSize, then nfunc, nfiles, textStart,
    funcnametab, cutab, filetab, pctab, funcdata offsets (pointer-sized);
    functab holds (entryOff, funcOff) pairs; each _func names its file
    through pcfile's first value and the compilation unit table.
    """

    if len(data) < 8 + 8 * 4:
        return []
    magic, = struct.unpack_from("<I", data, 0)
    if magic not in (0xFFFFFFF0, 0xFFFFFFF1):  # Go 1.18-1.19, 1.20+
        return []
    pointer = data[7]
    if pointer not in (4, 8):
        return []
    word = "<Q" if pointer == 8 else "<I"
    nfunc, _nfiles, _text, funcname, cutab, filetab, pctab, funcdata = (
        struct.unpack_from(word, data, 8 + i * pointer)[0] for i in range(8)
    )
    if nfunc > 10_000_000:
        return []

    def cstring(offset):
        end = data.find(b"\0", offset)
        return data[offset:end].decode("utf-8", "replace") if end >= 0 else ""

    def first_value(table):
        value = shift = 0
        index = pctab + table
        while index < len(data):
            byte = data[index]
            index += 1
            value |= (byte & 0x7F) << shift
            if byte < 0x80:
                break
            shift += 7
        return -1 + (-(value >> 1) - 1 if value & 1 else value >> 1)

    entries = []
    for index in range(nfunc + 1):
        entries.append(struct.unpack_from("<II", data, funcdata + index * 8))
    out = []
    for index in range(nfunc):
        entry_off, func_off = entries[index]
        base = funcdata + func_off
        if base + 40 > len(data):
            continue
        _entry, name_off, _args, _defer, _pcsp, pcfile, pcln, _npc, cu_off, start_line = struct.unpack_from(
            "<IiiIIIIIIi", data, base)
        name = cstring(funcname + name_off)
        file = None
        if pcfile:
            number = first_value(pcfile)
            if number >= 0:
                slot = cutab + (cu_off + number) * 4
                if slot + 4 <= len(data):
                    file_off, = struct.unpack_from("<I", data, slot)
                    if file_off != 0xFFFFFFFF:
                        file = cstring(filetab + file_off)
        line = start_line if magic == 0xFFFFFFF1 and start_line > 0 else (first_value(pcln) if pcln else None)
        size = entries[index + 1][0] - entry_off
        if file in ("<autogenerated>", ""):
            file = None
        out.append(((text_start or 0) + entry_off, max(size, 0), name, file, line if line and line > 0 else None))
    return out


def pclntab_text_start(data):
    """The textStart field of a pclntab header (0 in position-independent builds)."""

    if len(data) < 8 + 3 * 8 or data[7] not in (4, 8):
        return 0
    return struct.unpack_from("<Q" if data[7] == 8 else "<I", data, 8 + 2 * data[7])[0]


def text_start(path, data, offsets):
    """Address the pclntab's function offsets count from.

    The header's textStart when set (non-PIE builds); otherwise the offset that
    symbol-table names shared with the pclntab agree on (cgo builds export
    crosscall2 and friends, whose code sits after C code in .text); otherwise
    the start of .text.
    """

    header = pclntab_text_start(data)
    if header:
        return header
    from collections import Counter

    from xray.minidebug import read_function_table

    known = {name: address for address, _size, name in read_function_table(path)}
    votes = Counter(known[name] - offset for offset, name in offsets if name in known)
    if votes:
        return votes.most_common(1)[0][0]
    sections = _section_headers(path)
    return sections[".text"][0] if ".text" in sections else 0


def go_functions(path):
    """(functions, GoInfo) for a Go ELF binary, or (None, None)."""

    sections = _section_headers(path)
    if ".gopclntab" not in sections or ".text" not in sections:
        return None, None
    _address, offset, size = sections[".gopclntab"]
    try:
        with open(path, "rb") as handle:
            handle.seek(offset)
            data = handle.read(size)
    except OSError:
        return None, None
    raw = parse_pclntab(data)
    if not raw:
        return None, None
    base = text_start(path, data, [(address, name) for address, _s, name, _f, _l in raw])
    info = build_info(path)
    paths = normalise_paths({file for *_rest, file, _line in raw if file}, info)
    functions = [(base + offset, size, name, paths.get(file, file), line) for offset, size, name, file, line in raw]
    return functions, info


def _unescape_module(path):
    return re.sub(r"!([a-z])", lambda m: m.group(1).upper(), path)


def normalise_paths(files, info):
    """{absolute build path: the -trimpath form} for builds made without -trimpath.

    GOROOT/src/runtime/proc.go -> runtime/proc.go; .../pkg/mod/module@version/f.go ->
    module@version/f.go; the main module's checkout -> module/relative/path.
    """

    absolute = [file for file in files if file.startswith("/")]
    if not absolute:
        return {}
    roots = {file[: file.index("/src/runtime/") + 5] for file in absolute if "/src/runtime/" in file}
    goroot_src = min(roots, key=len) if roots else None
    out, rest = {}, []
    for file in absolute:
        if goroot_src and file.startswith(goroot_src):
            out[file] = file[len(goroot_src):]
        elif "/pkg/mod/" in file:
            out[file] = _unescape_module(file.split("/pkg/mod/", 1)[1])
        else:
            rest.append(file)
    if rest and info and info.module:
        import posixpath

        top = posixpath.commonpath(rest) if len(rest) > 1 else posixpath.dirname(rest[0])
        for file in rest:
            out[file] = f"{info.module}/{file[len(top):].lstrip('/')}"
    return out


def build_info(path):
    from xray.fingerprint import fingerprint

    try:
        found = fingerprint(path)
    except (OSError, ValueError):
        return GoInfo(None, None, None, None)
    module, version = (found.module.split(" ", 1) + [None])[:2] if found.module else (None, None)
    revision = next((s.split("=", 1)[1] for s in found.settings if s.startswith("vcs.revision=")), None)
    return GoInfo(found.toolchain, module, version, revision)


def go_base(name):
    """Readable Go name: pkg/path.(*T).M[...] -> path.T.M (module path dropped)."""

    name = re.sub(r"\[[^\[\]]*\]", "", name)
    name = name.replace(".(*", ".").replace(").", ".")
    head, _, tail = name.rpartition("/")
    return tail if head else name


def is_go_name(name):
    return "/" in name.split(".", 1)[0] or ".(*" in name or bool(re.match(r"^[a-z][\w]*\.[A-Za-z_(]", name))


def origin(file, info=None):
    """(group, label) for a Go source path."""

    match = _DEP.match(file)
    if match:
        return "dependency", f"{match['module']} {match['version']}"
    if file.startswith("_cgo_"):
        return "standard library", "cgo glue (generated)"
    if info and info.module and (file == info.module or file.startswith(info.module + "/")):
        return "program", None
    first = file.split("/", 1)[0]
    if "." not in first and not file.startswith("/"):
        return "standard library", "Go standard library"
    return "program", None


def short(file, info=None):
    match = _DEP.match(file)
    if match:
        return match["inner"]
    if info and info.module and file.startswith(info.module + "/"):
        return file[len(info.module) + 1:]
    return file


def escape_module(module):
    """Module proxy path escaping: upper-case letters become !lower."""

    return re.sub(r"[A-Z]", lambda m: "!" + m.group().lower(), module)


def _download(url, limit=_MAX_ZIP_BYTES):
    import urllib.request

    from xray import __version__

    request = urllib.request.Request(url, headers={"User-Agent": f"xray-trust/{__version__} (source viewer)"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read(limit + 1)


def _from_module_zip(module, version, inner, fetch):
    from xray.evidencestore import cache_dir

    if ".." in inner.split("/"):
        return None
    target = cache_dir() / "go" / "src" / f"{escape_module(module)}@{version}" / inner
    if target.is_file():
        return target
    archive = cache_dir() / "go" / "zip" / f"{escape_module(module)}@{version}.zip"
    if not archive.is_file():
        try:
            data = fetch(f"{PROXY}/{escape_module(module)}/@v/{version}.zip")
        except OSError:
            return None
        if not data or len(data) > _MAX_ZIP_BYTES:
            return None
        archive.parent.mkdir(parents=True, exist_ok=True)
        archive.write_bytes(data)
    import zipfile

    try:
        with zipfile.ZipFile(archive) as bundle:
            content = bundle.read(f"{module}@{version}/{inner}")
    except (KeyError, OSError, zipfile.BadZipFile):
        return None
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content)
    return target


def source(file, info, fetch=None):
    """(local path, where) for a Go source file, or (None, reason)."""

    fetch = fetch or _download
    match = _DEP.match(file)
    if match:
        found = _from_module_zip(match["module"], match["version"], match["inner"], fetch)
        return (found, "the Go module proxy") if found else (None, "not on the Go module proxy")
    if info and info.module and file.startswith(info.module + "/"):
        version = (info.version or "").split("+", 1)[0]
        if not _SEMVER.match(version):
            return None, f"the main module's version ({info.version}) is not a release on the module proxy"
        found = _from_module_zip(info.module, version, file[len(info.module) + 1:], fetch)
        if found is None:
            return None, f"{info.module}@{version} is not on the Go module proxy"
        note = " (this build was marked +dirty: distribution patches may differ)" if "+dirty" in (info.version or "") else ""
        return found, f"the Go module proxy, {info.module}@{version}{note}"
    tag = _GO_TAG.match(info.go_version or "") if info else None
    if tag and ".." not in file.split("/"):
        from xray.evidencestore import cache_dir

        target = cache_dir() / "go" / "goroot" / tag.group() / file
        if target.is_file():
            return target, f"the Go repository ({tag.group()})"
        try:
            data = fetch(GO_SOURCE.format(tag=tag.group(), inner=file), limit=16 * 1024 * 1024)
        except OSError:
            return None, f"not found in the Go repository at {tag.group()}"
        if not data:
            return None, "empty file"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        return target, f"the Go repository ({tag.group()})"
    return None, "unknown origin"
