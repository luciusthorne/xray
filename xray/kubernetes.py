"""Kubernetes manifests from a capability contract.

`xray contract kubernetes CONTRACT` writes a Pod whose container runs the
contract's program with what Kubernetes can enforce of the contract:

- securityContext: no privilege escalation, a read-only root file system,
  non-root, every capability dropped (NET_BIND_SERVICE kept only for a bind
  below port 1024);
- [write] locations become emptyDir volumes (the only writable places);
- [syscalls] becomes a seccomp profile (Localhost, written next to the
  manifest); without denials the runtime's default profile is used;
- [net] becomes a NetworkPolicy: `none` denies all traffic, connect/bind ports
  are the only egress/ingress allowed, `any` adds no policy.

What Kubernetes cannot express is said in comments: per-file read and exec
rights (Landlock) stay with `xray contract enforce` inside the container.
"""

import json
import re
from pathlib import PurePosixPath

PRIVILEGED_PORTS = 1024


def resource_name(program):
    """A DNS-1123 label from the program's file name."""

    name = re.sub(r"[^a-z0-9-]+", "-", PurePosixPath(program).name.lower()).strip("-")
    return (name or "program")[:63].rstrip("-") or "program"


def _write_roots(contract):
    """Directories to mount writable, from [write] (globs and files reduce to their directory)."""

    roots = set()
    for value in contract.values("write"):
        if value.startswith("~"):
            continue
        path = value.split("*", 1)[0].rstrip("/") if "*" in value else value
        if "*" not in value and PurePosixPath(path).suffix:
            path = str(PurePosixPath(path).parent)
        roots.add(path or "/")
    kept = []
    for root in sorted(roots, key=len):
        if root == "/" or not any(root == other or root.startswith(other.rstrip("/") + "/") for other in kept):
            kept.append(root)
    return [root for root in kept if root != "/"], any(value.startswith("~") for value in contract.values("write"))


def _ports(contract):
    """{"connect": [(protocol, port or None)], "bind": [...]}, and whether [net] is any."""

    out = {"connect": [], "bind": []}
    values = contract.values("net")
    for value in values:
        parts = value.split()
        if len(parts) == 3 and parts[0] in out:
            out[parts[0]].append((parts[1].upper(), None if parts[2] == "*" else int(parts[2])))
    return out, "any" in values, not values


def seccomp_profile(contract):
    """The Localhost seccomp profile (JSON text) for [syscalls], or None without denials."""

    denied = [entry.value for entry in contract.sections.get("syscalls", [])]  # [syscalls] is contract version 2
    if not denied:
        return None
    return json.dumps({
        "defaultAction": "SCMP_ACT_ALLOW",
        "architectures": ["SCMP_ARCH_X86_64"],
        "syscalls": [{"names": sorted(denied), "action": "SCMP_ACT_ERRNO", "errnoRet": 1}],
    }, indent=2) + "\n"


def _q(value):
    return json.dumps(value)  # a JSON string is a valid YAML scalar


def manifests(contract, name=None, image=None, args=()):
    """Multi-document YAML: the Pod and, unless [net] is any, its NetworkPolicy."""

    name = name or resource_name(contract.program)
    profile = seccomp_profile(contract)
    roots, home_writes = _write_roots(contract)
    ports, net_any, net_none = _ports(contract)
    low_bind = any(port is None or port < PRIVILEGED_PORTS for _protocol, port in ports["bind"])

    lines = [
        f"# Generated by xray from the capability contract for {contract.program}",
        "# Kubernetes enforces the parts below; per-file read/exec rights stay with",
        "# `xray contract enforce` (Landlock) inside the container.",
        "apiVersion: v1",
        "kind: Pod",
        "metadata:",
        f"  name: {_q(name)}",
        "  labels:",
        f"    app: {_q(name)}",
        "spec:",
        "  automountServiceAccountToken: false",
        "  securityContext:",
        "    runAsNonRoot: true",
        "    seccompProfile:",
    ]
    if profile:
        lines += [
            "      type: Localhost",
            f"      localhostProfile: {_q(f'xray/{name}.json')}  # copy {name}.seccomp.json to <kubelet>/seccomp/xray/{name}.json",
        ]
    else:
        lines.append("      type: RuntimeDefault")
    lines += [
        "  containers:",
        f"    - name: {_q(name)}",
        f"      image: {_q(image or 'REPLACE-WITH-YOUR-IMAGE')}" + ("" if image else "  # the image that contains the program"),
        f"      command: {json.dumps([contract.program, *args])}",
        "      securityContext:",
        "        allowPrivilegeEscalation: false",
        "        readOnlyRootFilesystem: true",
        "        capabilities:",
        '          drop: ["ALL"]',
    ]
    if low_bind:
        lines.append('          add: ["NET_BIND_SERVICE"]  # the contract binds a port below 1024')
    if roots:
        lines.append("      volumeMounts:")
        for index, root in enumerate(roots):
            lines += [f"        - name: {_q(f'write-{index}')}", f"          mountPath: {_q(root)}"]
    if home_writes:
        lines.append("      # the contract writes under the home directory: mount a volume at the container user's home")
    if roots:
        lines.append("  volumes:")
        for index, _root in enumerate(roots):
            lines += [f"    - name: {_q(f'write-{index}')}", "      emptyDir: {}"]
    if net_any:
        lines.append("# [net] is any: no NetworkPolicy")
        return "\n".join(lines) + "\n", profile

    def rules(kind, direction):
        entries = ports[kind]
        if not entries:
            return [f"  {direction}: []"]
        out = [f"  {direction}:", "    - ports:"]
        for protocol, port in entries:
            out.append(f"        - protocol: {protocol}" + (f"\n          port: {port}" if port is not None else ""))
        return out

    lines += [
        "---",
        "apiVersion: networking.k8s.io/v1",
        "kind: NetworkPolicy",
        "metadata:",
        f"  name: {_q(name)}",
        "spec:",
        "  podSelector:",
        "    matchLabels:",
        f"      app: {_q(name)}",
        '  policyTypes: ["Ingress", "Egress"]',
    ]
    if net_none:
        lines.append("  # [net] is none: no traffic in or out")
    lines += rules("bind", "ingress")
    lines += rules("connect", "egress")
    if ports["connect"]:
        lines.append("  # name lookups need DNS: add UDP/TCP 53 to egress if the program resolves names")
    return "\n".join(lines) + "\n", profile
