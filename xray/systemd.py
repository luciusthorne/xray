"""A capability contract as systemd sandboxing settings.

The contract becomes a unit (or a drop-in for an existing service) that
systemd enforces itself, with no XRAY at run time:

- [exec] and [load] -> NoExecPaths=/ and ExecPaths= for exactly those files,
  so nothing else can be executed or mapped as code;
- [write] -> ProtectSystem=strict with ReadWritePaths= for each entry, and
  a private /tmp unless the contract writes there;
- the home directory -> ProtectHome=read-only, with BindPaths= for each
  [write] entry under it; with hide_home, ProtectHome=tmpfs and
  BindReadOnlyPaths= for each [read] entry instead (programs that test
  whether other files exist may then take another path: Landlock lets a
  program see that a file exists without reading it, a hidden home does not);
- [net] -> PrivateNetwork=yes for none; RestrictAddressFamilies= for
  unix, tcp and udp; SocketBindAllow= for bind entries;
- always NoNewPrivileges=yes, RestrictSUIDSGID=yes, LockPersonality=yes.

systemd's directives make files read-only, not unreadable: reads are not
limited (except under a hidden home); `xray contract enforce` (Landlock)
limits them.
"""

from __future__ import annotations

import shlex
from pathlib import Path

from .contract import expand_home


def _root(value, home):
    value = expand_home(value, home)
    if value.endswith("/**"):
        return value[:-3] or "/"
    if any(ch in Path(value).name for ch in "*?["):
        return str(Path(value).parent)
    return value


def _quote(path):
    return f'"{path}"' if " " in path else path


def directives(contract, home="%h", hide_home=False):
    """[(key, value)] sandbox settings for the contract. Home paths use %h (the user's home)."""

    def resolve(value):
        if value.startswith("~/") and home == "%h":
            # reduce dir/** and glob entries to their directory first, then spell the home as %h
            return "%h" + _root(value, "/HOME")[len("/HOME"):]
        return _root(value, None if not value.startswith("~/") else home)

    out = [("NoNewPrivileges", "yes"), ("RestrictSUIDSGID", "yes"), ("LockPersonality", "yes"),
           ("ProtectSystem", "strict")]
    denied = list(contract.values("syscalls"))
    if denied:
        out.append(("SystemCallFilter", "~" + " ".join(denied)))
        out.append(("SystemCallErrorNumber", "EPERM"))
    executable = sorted({resolve(value) for section in ("exec", "load") for value in contract.values(section)})
    out.append(("NoExecPaths", "/"))
    out.append(("ExecPaths", " ".join(_quote(path) for path in executable)))
    home_reads = [resolve(value) for value in contract.values("read") if value.startswith("~/")]
    home_writes = [resolve(value) for value in contract.values("write") if value.startswith("~/")]
    if hide_home:
        out.append(("ProtectHome", "tmpfs"))
        for path in home_reads:
            out.append(("BindReadOnlyPaths", f"-{_quote(path)}"))
    else:
        out.append(("ProtectHome", "read-only"))
    for path in home_writes:
        out.append(("BindPaths", f"-{_quote(path)}"))
    writes = [resolve(value) for value in contract.values("write") if not value.startswith("~/")]
    if not any(path == "/tmp" or path.startswith("/tmp/") for path in writes):
        out.append(("PrivateTmp", "yes"))
    for path in writes:
        out.append(("ReadWritePaths", f"-{_quote(path)}"))

    net = contract.values("net")
    if not net or net == ["none"]:
        out.append(("PrivateNetwork", "yes"))
        out.append(("RestrictAddressFamilies", "AF_UNIX"))
    elif "any" not in net:
        families = {"AF_UNIX"} if "unix" in net else set()
        if any(value.split()[1:2] in (["tcp"], ["udp"]) for value in net):
            families |= {"AF_INET", "AF_INET6"}
        out.append(("RestrictAddressFamilies", " ".join(sorted(families)) or "none"))
        binds = [value.split() for value in net if value.startswith("bind ")]
        if binds:
            for _bind, protocol, port in binds:
                out.append(("SocketBindAllow", f"{protocol}:{port}" if port != "*" else protocol))
            out.append(("SocketBindDeny", "any"))
    return out


def unit(contract, args=(), name=None, dropin=False, hide_home=False):
    """A service unit (or, with dropin, a [Service] drop-in) running the program under the contract."""

    lines = [f"# Generated by xray from the capability contract for {contract.program}"]
    if contract.sha256:
        lines.append(f"# program sha256 {contract.sha256}")
    if not dropin:
        lines += ["[Unit]", f"Description={name or Path(contract.program).name} (held to its XRAY contract)", ""]
    lines.append("[Service]")
    if not dropin:
        lines.append("Type=exec")
        lines.append("ExecStart=" + " ".join(shlex.quote(part) for part in [contract.program, *args]))
    lines += [f"{key}={value}" for key, value in directives(contract, hide_home=hide_home)]
    return "\n".join(lines) + "\n"


def run_properties(contract, home, hide_home=False):
    """The same settings as --property arguments for systemd-run, with the home directory spelled out."""

    return [f"{key}={value}" for key, value in directives(contract, home=home, hide_home=hide_home)]


def run_command(contract, args, hide_home=False, environ=None):
    """The systemd-run argv that runs the program under these settings, with the caller's desktop environment."""

    import os

    environ = os.environ if environ is None else environ
    passed = [key for key in environ if key.startswith(("XDG_", "LC_")) or key in (
        "LANG", "LANGUAGE", "PATH", "DESKTOP_SESSION", "DISPLAY", "WAYLAND_DISPLAY", "TERM", "HOME", "USER")]
    return ["systemd-run", "--user", "--wait", "--pipe", "--collect", "--quiet",
            *[f"--setenv={key}" for key in sorted(passed)],
            *[f"--property={item}" for item in run_properties(contract, str(Path.home()), hide_home)],
            "--", contract.program, *args]
