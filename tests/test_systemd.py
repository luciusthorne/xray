import shutil
import subprocess

import pytest

from xray import systemd
from xray.contract import parse_contract
from xray.contractgen import add_observed
from xray.observe import Observed, parse_capabilities

CONTRACT = """xray-contract 1
program /usr/bin/tool
[exec]
/usr/bin/tool
/usr/bin/grep
[load]
/usr/lib/libc.so.6
[read]
~/.config/tool.conf
/etc/tool.conf
[write]
~/.cache/tool/**
/var/lib/tool/**
[net]
connect tcp 443
bind tcp 8080
"""


def settings(text=CONTRACT, **options):
    return systemd.directives(parse_contract(text), **options)


def test_exec_load_write_and_net_map_to_systemd():
    found = settings()

    assert ("NoExecPaths", "/") in found
    assert ("ExecPaths", "/usr/bin/grep /usr/bin/tool /usr/lib/libc.so.6") in found
    assert ("ProtectSystem", "strict") in found and ("ProtectHome", "read-only") in found
    assert ("BindPaths", "-%h/.cache/tool") in found
    assert ("ReadWritePaths", "-/var/lib/tool") in found
    assert ("PrivateTmp", "yes") in found
    assert ("RestrictAddressFamilies", "AF_INET AF_INET6") in found
    assert ("SocketBindAllow", "tcp:8080") in found and ("SocketBindDeny", "any") in found


def test_hidden_home_binds_only_the_contract_reads_and_no_network_is_private():
    found = settings(CONTRACT.split("[net]")[0] + "[net]\nnone\n", hide_home=True)

    assert ("ProtectHome", "tmpfs") in found
    assert ("BindReadOnlyPaths", "-%h/.config/tool.conf") in found
    assert ("PrivateNetwork", "yes") in found


def test_unit_text():
    text = systemd.unit(parse_contract(CONTRACT), ["--serve", "x y"])

    assert "ExecStart=/usr/bin/tool --serve 'x y'" in text
    assert text.startswith("# Generated by xray") and "[Service]" in text
    assert "ExecStart" not in systemd.unit(parse_contract(CONTRACT), dropin=True)


@pytest.mark.skipif(shutil.which("systemd-analyze") is None, reason="needs systemd-analyze")
def test_generated_unit_verifies(tmp_path):
    unit = tmp_path / "tool-contract.service"
    unit.write_text(systemd.unit(parse_contract(CONTRACT.replace("/usr/bin/tool", "/usr/bin/true"))))

    done = subprocess.run(["systemd-analyze", "verify", "--user", str(unit)], capture_output=True, text=True,
                          check=False)

    assert "Unknown key" not in done.stderr and "Invalid" not in done.stderr


def test_execute_permission_probes_are_traced_and_listed(tmp_path):
    observed = parse_capabilities(
        '10 faccessat2(AT_FDCWD, "/usr/bin/nvim", X_OK, AT_EACCESS) = 0\n'
        '10 access("/etc/passwd", R_OK) = 0\n', "/")

    assert observed.probed == ["/usr/bin/nvim"]
    target = tmp_path / "nvim"
    target.write_text("x")
    contract = add_observed(parse_contract("xray-contract 1\nprogram /usr/bin/tool\n"),
                            Observed(probed=[str(target)]), home=str(tmp_path / "home"))
    assert contract.sections["exec"][0].comment == "observed: tested as executable (test -x)"
